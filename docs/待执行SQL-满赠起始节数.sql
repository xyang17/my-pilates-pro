-- ============================================================
-- 满课赠送：每个学员的「历史已累计节数」
-- ============================================================
-- 用途：老学员在用这个系统之前就上过课，可以给他认一个起始节数。
--      比如廖一之前已经上了 16 节，填 16，那她再上 4 节就满 20。
--
-- 执行方式：Supabase 后台 → 左侧 SQL Editor → 粘贴 → Run
-- 执行前后都不影响现有功能：代码里读不到这个字段时按 0 处理。
-- ============================================================

ALTER TABLE "user"
  ADD COLUMN IF NOT EXISTS loyalty_base_count INTEGER NOT NULL DEFAULT 0;

COMMENT ON COLUMN "user".loyalty_base_count IS
  '满课赠送的起始节数：用系统之前就上过的课，由教练手工认定。实际累计 = 这个值 + 系统里已完成的课数';

